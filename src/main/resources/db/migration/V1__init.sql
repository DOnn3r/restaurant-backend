-- (types, longueurs, contraintes), plus des index pour les requêtes fréquentes.
-- Ne jamais modifier ce fichier une fois appliqué : ajouter un nouveau V2__..., V3__...

CREATE TABLE app_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(255) NOT NULL,
    role          VARCHAR(255) NOT NULL,
    active        BOOLEAN      NOT NULL,
    CONSTRAINT uk_app_users_username UNIQUE (username),
    CONSTRAINT ck_app_users_role CHECK (role IN ('ADMIN', 'SERVEUR', 'CUISINIER'))
);

CREATE TABLE dining_tables (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label VARCHAR(255) NOT NULL,
    seats INTEGER      NOT NULL,
    CONSTRAINT uk_dining_tables_label UNIQUE (label)
);

CREATE TABLE dishes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255)   NOT NULL,
    description VARCHAR(500),
    price       NUMERIC(10, 2) NOT NULL,
    category    VARCHAR(255)   NOT NULL,
    available   BOOLEAN        NOT NULL
);

CREATE TABLE dish_ingredients (
    dish_id    BIGINT NOT NULL,
    ingredient VARCHAR(255),
    CONSTRAINT fk_dish_ingredients_dish FOREIGN KEY (dish_id) REFERENCES dishes (id) ON DELETE CASCADE
);
CREATE INDEX idx_dish_ingredients_dish ON dish_ingredients (dish_id);

CREATE TABLE customer_orders (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dining_table_id BIGINT       NOT NULL,
    server_id       BIGINT       NOT NULL,
    status          VARCHAR(255) NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    paid_at         TIMESTAMP(6) WITH TIME ZONE,
    payment_method  VARCHAR(255),
    CONSTRAINT fk_orders_table  FOREIGN KEY (dining_table_id) REFERENCES dining_tables (id),
    CONSTRAINT fk_orders_server FOREIGN KEY (server_id)       REFERENCES app_users (id),
    CONSTRAINT ck_orders_status CHECK (status IN ('OPEN', 'PAID', 'CANCELLED')),
    CONSTRAINT ck_orders_payment CHECK (payment_method IN ('CASH', 'CARD', 'OTHER'))
);
CREATE INDEX idx_orders_table_status ON customer_orders (dining_table_id, status);
CREATE INDEX idx_orders_status_created ON customer_orders (status, created_at);
CREATE INDEX idx_orders_status_paid ON customer_orders (status, paid_at);
CREATE INDEX idx_orders_server ON customer_orders (server_id);

CREATE TABLE order_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT         NOT NULL,
    dish_id    BIGINT,
    dish_name  VARCHAR(255)   NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,
    quantity   INTEGER        NOT NULL,
    note       VARCHAR(300),
    status     VARCHAR(255)   NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_items_order FOREIGN KEY (order_id) REFERENCES customer_orders (id),
    CONSTRAINT fk_items_dish  FOREIGN KEY (dish_id)  REFERENCES dishes (id),
    CONSTRAINT ck_items_status CHECK (status IN ('PENDING', 'PREPARING', 'READY', 'SERVED'))
);
CREATE INDEX idx_items_order ON order_items (order_id);
CREATE INDEX idx_items_dish ON order_items (dish_id);

CREATE TABLE expenses (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label    VARCHAR(255)   NOT NULL,
    category VARCHAR(255)   NOT NULL,
    amount   NUMERIC(10, 2) NOT NULL,
    date     DATE           NOT NULL
);
CREATE INDEX idx_expenses_date ON expenses (date);
